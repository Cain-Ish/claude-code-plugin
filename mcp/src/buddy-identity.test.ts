import { describe, it, expect } from 'vitest';
import {
  wyhash64, hashString, mulberry32, generateBones, renderCard, defaultName,
  SPECIES, EYES, HATS, RARITIES, SALT, NAMES,
} from './buddy-identity.js';

// Zig std/hash/wyhash.zig (v4.2) reference vectors — the SAME implementation Bun.hash wraps,
// which is what Claude Code's native /buddy seeded from. If these hold, the bones match.
const ZIG_VECTORS: Array<[bigint, string, bigint]> = [
  [0n, '', 0x409638ee2bde459n],
  [1n, 'a', 0xa8412d091b5fe0a9n],
  [2n, 'abc', 0x32dd92e4b2915153n],
  [3n, 'message digest', 0x8619124089a3a16bn],
  [4n, 'abcdefghijklmnopqrstuvwxyz', 0x7a43afb61d7f5f40n],
  [5n, 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789', 0xff42329b90e50d58n],
  [6n, '12345678901234567890123456789012345678901234567890123456789012345678901234567890', 0xc39cab13b115aad3n],
];

describe('wyhash64 (Zig v4.2 / Bun.hash parity)', () => {
  for (const [seed, input, expected] of ZIG_VECTORS) {
    it(`seed=${seed} len=${input.length}`, () => {
      expect(wyhash64(input, seed)).toBe(expected);
    });
  }
  it('covers every length class (0-3, 4-16, 17-48, 48+ with tail)', () => {
    // Just determinism + no throw across the branch boundaries; the vectors above pin values.
    for (const n of [0, 1, 3, 4, 8, 16, 17, 47, 48, 49, 96, 97, 130]) {
      const s = 'x'.repeat(n);
      expect(wyhash64(s)).toBe(wyhash64(s));
    }
  });
});

describe('mulberry32', () => {
  it('is deterministic and in [0,1)', () => {
    const a = mulberry32(12345), b = mulberry32(12345);
    for (let i = 0; i < 100; i++) { const x = a(); expect(x).toBe(b()); expect(x).toBeGreaterThanOrEqual(0); expect(x).toBeLessThan(1); }
  });
  it('handles seeds above 2^31 (>>> 0 coercion)', () => {
    expect(() => mulberry32(0xffffffff)()).not.toThrow();
  });
});

describe('generateBones', () => {
  const id = '0f7a2d9e-6c1b-4b3e-9a8d-1234567890ab';
  it('is a pure function of id + salt', () => {
    expect(generateBones(id)).toEqual(generateBones(id));
    expect(generateBones(id)).not.toEqual(generateBones(id + '1'));
    expect(generateBones(id, 'other-salt')).not.toEqual(generateBones(id));
  });
  it('uses the original 18 species in the original order (pick divides by length)', () => {
    expect(SPECIES.length).toBe(18);
    expect(SPECIES[0]).toBe('duck'); expect(SPECIES[2]).toBe('blob'); expect(SPECIES[17]).toBe('chonk');
    expect(EYES.length).toBe(6); expect(HATS.length).toBe(8); expect(HATS[0]).toBe('none');
  });
  it('pins a known vector so a refactor cannot silently change every user\'s buddy', () => {
    // Generated by this implementation once the Zig vectors passed; treat as a lock, not a spec.
    const b = generateBones(id);
    expect(hashString(id + SALT)).toBe(hashString(id + SALT));
    expect(RARITIES).toContain(b.rarity); expect(SPECIES).toContain(b.species);
    expect(EYES).toContain(b.eye); expect(HATS).toContain(b.hat);
    // Also asserted by tests/test-buddy-statusline.sh against the built CLI bundle.
    expect(b).toEqual({ rarity: 'uncommon', species: 'dragon', eye: '@', hat: 'tophat', shiny: false });
    expect(defaultName(id)).toBe('Tofu');
    expect(NAMES).toContain(defaultName('anyone-else'));
  });
  it('respects the rarity weights and the common→no-hat rule across many ids', () => {
    let commons = 0, hats = 0, legendary = 0;
    const N = 4000;
    for (let i = 0; i < N; i++) {
      const b = generateBones(`user-${i}`);
      if (b.rarity === 'common') { commons++; expect(b.hat).toBe('none'); }
      if (b.hat !== 'none') hats++;
      if (b.rarity === 'legendary') legendary++;
    }
    // 60 % common ± a wide margin; ≥1 legendary in 4000 (p≈1 %) — sanity, not statistics.
    expect(commons / N).toBeGreaterThan(0.5); expect(commons / N).toBeLessThan(0.7);
    expect(hats).toBeGreaterThan(0); expect(legendary).toBeGreaterThan(0);
  });
});

describe('renderCard', () => {
  it('is one line: name, rarity, species, stars (no stat sheet — not what this buddy is for)', () => {
    const b = generateBones('card-test');
    const card = renderCard(b, 'Ziutek');
    expect(card.split('\n')).toHaveLength(1);
    expect(card).toContain('Ziutek'); expect(card).toContain(b.species); expect(card).toContain(b.rarity); expect(card).toContain('★');
  });
});
