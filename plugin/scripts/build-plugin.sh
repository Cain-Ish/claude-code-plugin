#!/bin/bash
# build-plugin.sh — assemble the shipped plugin tree (plugin/) from .claude-plugin/ship-manifest.txt.
#
# Why: a marketplace install copies the WHOLE `source` directory and Claude Code has no ignore or
# allowlist mechanism, so with `source: "./"` every user received tests/, docs/, mcp/src/, .claude/
# and friends (~8 MB, half of it dev material). `source: "./plugin"` ships only what this script
# puts there. plugin/ is committed (an installer reads the repo as-is); the drift gate
# tests/test-plugin-dist-current.sh keeps it honest — "prose promises need machine locks".
#
# Usage:  bash scripts/build-plugin.sh            rebuild plugin/ in place (atomic swap)
#         bash scripts/build-plugin.sh --check    build to a temp dir and diff against plugin/;
#                                                 exit 1 and list the drift (never writes plugin/)
#         bash scripts/build-plugin.sh --out DIR  build into DIR (used by the gate)
# Portability: bash 3.2+, no globstar, no rsync, no `cp --parents` — file lists come from `find`
# and are copied with `tar` (git-bash, macOS BSD tar, GNU tar all accept this form).
set -u
ROOT="$(cd "$(dirname "$0")"/.. && pwd)"
MANIFEST="$ROOT/.claude-plugin/ship-manifest.txt"
OUT="$ROOT/plugin"; MODE="build"
while [ $# -gt 0 ]; do
  case "$1" in
    --check) MODE="check" ;;
    --out) shift; OUT="${1:?--out needs a directory}" ;;
    *) echo "build-plugin: unknown arg $1" >&2; exit 2 ;;
  esac; shift
done
[ -f "$MANIFEST" ] || { echo "build-plugin: manifest missing: $MANIFEST" >&2; exit 2; }

# List every shipped file, one relative path per line, from the manifest. The manifest walk
# runs in a command substitution, not as a pipeline stage: a `return 1` from a pipeline stage
# is lost (no pipefail), so a missing entry used to print an error, drop every later entry
# and still exit 0.
manifest_paths() {
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%%#*}"; line="${line%"${line##*[! ]}"}"   # strip comments + trailing spaces
    [ -n "$line" ] || continue
    local path="${line%% *}" pat=""
    case "$line" in *" "*) pat="${line#* }" ;; esac
    case "$path" in
      */)
        [ -d "$ROOT/$path" ] || { echo "build-plugin: manifest dir missing: $path" >&2; return 1; }
        if [ -n "$pat" ]; then find "$ROOT/$path" -type f -name "$pat"; else find "$ROOT/$path" -type f; fi ;;
      *)
        [ -f "$ROOT/$path" ] || { echo "build-plugin: manifest file missing: $path" >&2; return 1; }
        printf '%s\n' "$ROOT/$path" ;;
    esac
  done < "$MANIFEST"
}
list_files() {
  local raw; raw=$(manifest_paths) || return 1
  printf '%s\n' "$raw" \
  | sed "s#^$ROOT/##" \
  | grep -Ev '(^|/)(node_modules/|\.DS_Store$|Thumbs\.db$)|\.stackdump$|\.tmp\.[0-9]+$' \
  | LC_ALL=C sort -u
}

build_into() {  # $1 = destination dir (must not exist or be empty)
  local dest="$1"
  mkdir -p "$dest" || return 1
  local list; list=$(list_files) || return 1
  [ -n "$list" ] || { echo "build-plugin: manifest produced no files" >&2; return 1; }
  ( cd "$ROOT" && printf '%s\n' "$list" | tar -cf - -T - ) | tar -xf - -C "$dest" || return 1
  # A short README so the marketplace card and the cache dir explain themselves.
  cat > "$dest/README.md" <<'README'
# second-brain — shipped plugin tree

This directory is GENERATED by `scripts/build-plugin.sh` from `.claude-plugin/ship-manifest.txt`
in the repository root; it contains only the files a Claude Code install needs. Do not edit here —
edit the source at the repository root and rebuild (`make build-plugin`). Source, tests, design
docs and the constitution: https://github.com/Cain-Ish/claude-code-plugin
README
  printf '%s\n' "$list" > "$dest/.ship-manifest.lock"
  return 0
}

case "$MODE" in
  build)
    TMP="$OUT.build.$$"; rm -rf "$TMP"
    build_into "$TMP" || { rm -rf "$TMP"; exit 1; }
    # Swap by rename, delete last: on Windows `rm -rf plugin/` fails partway when a file inside is
    # open, which used to leave a gutted plugin/ AND discard the fresh build.
    OLD="$OUT.old.$$"
    if [ -e "$OUT" ]; then
      mv "$OUT" "$OLD" || { rm -rf "$TMP"; echo "build-plugin: cannot move $OUT aside (a file in it is open?) — left untouched" >&2; exit 1; }
    fi
    mv "$TMP" "$OUT" || { [ -e "$OLD" ] && mv "$OLD" "$OUT"; rm -rf "$TMP"; exit 1; }
    rm -rf "$OLD" || echo "build-plugin: WARNING stale $OLD left behind — delete it before git add" >&2
    n=$(wc -l < "$OUT/.ship-manifest.lock" | tr -d ' ')
    echo "build-plugin: $OUT rebuilt — $n files"
    ;;
  check)
    TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
    build_into "$TMP/plugin" || exit 1
    [ -d "$OUT" ] || { echo "build-plugin --check: $OUT does not exist — run: bash scripts/build-plugin.sh" >&2; exit 1; }
    if DRIFT=$(diff -rq "$TMP/plugin" "$OUT" 2>&1); then
      echo "build-plugin --check: plugin/ is current"
    else
      echo "build-plugin --check: plugin/ DRIFTS from the manifest build — run: bash scripts/build-plugin.sh" >&2
      printf '%s\n' "$DRIFT" | sed "s#$TMP/plugin#<build>#g; s#$OUT#plugin#g" >&2
      exit 1
    fi
    ;;
esac
