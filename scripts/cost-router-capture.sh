#!/bin/bash
# scripts/cost-router-capture.sh
# Contract B consumer: reads cost-router-events.jsonl and writes/refreshes a
# bounded markdown summary to the wiki at wiki/state/cost-routing-patterns.md.
#
# Events path: ${COST_ROUTER_EVENTS:-${BRAIN_DIR:-$HOME/.second-brain}/cost-router-events.jsonl}
# Output:      ${SB_KNOWLEDGE_DIR:-${KNOWLEDGE_DIR:-$HOME/knowledge}}/wiki/state/cost-routing-patterns.md
#   (R5.1: wiki/state/ — root-level pages are never indexed by search; written
#    born-valid via sb_write_generated_page so knowledge_validate stops churning it)
#
# No-op if the events file is absent (zero cost when cost-router not installed).
# Never errors loudly — always exits 0.
#
# Bash 3.2 / BSD-safe: no mapfile, no assoc arrays, no date -d, no grep -P.

set -u
# Nested-spawn circuit breaker (R1.1): inside a plugin-spawned headless session, capture/context hooks no-op.
[ "${SB_NESTED_SPAWN:-0}" = "1" ] && exit 0

# ── Resolve paths ──────────────────────────────────────────────────────────────

_BRAIN_DIR="${SB_BRAIN_DIR:-${BRAIN_DIR:-$HOME/.second-brain}}"
_EVENTS="${COST_ROUTER_EVENTS:-$_BRAIN_DIR/cost-router-events.jsonl}"

# ── Guard: no-op when events file absent — BEFORE sourcing lib.sh ─────────────
# lib.sh is ~330ms+ to source; on every Stop hook the overwhelmingly common case
# is "cost-router not installed" → this events file simply does not exist. Bail
# here so the Stop hook pays nothing. The check depends ONLY on $_EVENTS
# (COST_ROUTER_EVENTS env, or $_BRAIN_DIR resolved above) — neither needs lib.sh.
if [ ! -f "$_EVENTS" ]; then
  exit 0
fi

# Knowledge dir: SB_KNOWLEDGE_DIR > KNOWLEDGE_DIR > CLAUDE_PLUGIN_OPTION_KNOWLEDGE_DIR > $HOME/knowledge
# (resolved here, still ahead of the source, so it keeps its SB_KNOWLEDGE_DIR alias precedence —
#  intentionally NOT sb_knowledge_dir, which has no SB_KNOWLEDGE_DIR tier and isn't defined yet.)
_KDIR="${SB_KNOWLEDGE_DIR:-${KNOWLEDGE_DIR:-${CLAUDE_PLUGIN_OPTION_KNOWLEDGE_DIR:-$HOME/knowledge}}}"
_KDIR="${_KDIR/#\~/$HOME}"

_OUT="$_KDIR/wiki/state/cost-routing-patterns.md"

# lib.sh provides sb_write_generated_page (born-valid frontmatter).
# Defensive source: a missing lib must not break the Stop hook.
if ! source "$(dirname "$0")/lib.sh" 2>/dev/null; then
  exit 0
fi

# ── Check jq available ────────────────────────────────────────────────────────

if ! command -v jq >/dev/null 2>&1; then
  exit 0
fi

# ── Aggregate events ──────────────────────────────────────────────────────────

# Guard: skip if file is empty
_LINES=$(wc -l < "$_EVENTS" 2>/dev/null | tr -d ' ')
_LINES="${_LINES:-0}"
if [ "$_LINES" -eq 0 ]; then
  exit 0
fi

# Cap at the last 500 events to keep summary bounded, then slurp into a temp var
_WINDOW=$(tail -n 500 "$_EVENTS" 2>/dev/null || true)
if [ -z "$_WINDOW" ]; then
  exit 0
fi

# Total events (in the 500-event window)
_TOTAL=$(printf '%s\n' "$_WINDOW" | jq -s 'length' 2>/dev/null || echo 0)

# Counts by tier — jq -rs slurps JSONL, extracts field, grep counts
_DO_COUNT=$(printf '%s\n' "$_WINDOW" | jq -rs '.[].tier' 2>/dev/null | tr -d '\r' | grep -c '^DO$' || true)
_THINK_COUNT=$(printf '%s\n' "$_WINDOW" | jq -rs '.[].tier' 2>/dev/null | tr -d '\r' | grep -c '^THINK$' || true)
_SCOUT_COUNT=$(printf '%s\n' "$_WINDOW" | jq -rs '.[].tier' 2>/dev/null | tr -d '\r' | grep -c '^SCOUT$' || true)

# Escalation counts
_ESCALATED=$(printf '%s\n' "$_WINDOW" | jq -rs '.[].escalated' 2>/dev/null | tr -d '\r' | grep -c '^true$' || true)
_ESCALATE_RATE=$(awk -v e="$_ESCALATED" -v t="$_TOTAL" 'BEGIN {
  if (t > 0) printf "%.0f%%", (e / t) * 100
  else print "0%"
}')

# Outcome counts
_OK_COUNT=$(printf '%s\n' "$_WINDOW" | jq -rs '.[].outcome' 2>/dev/null | tr -d '\r' | grep -c '^ok$' || true)

# Committed count
_COMMITTED=$(printf '%s\n' "$_WINDOW" | jq -rs '.[].committed' 2>/dev/null | tr -d '\r' | grep -c '^true$' || true)

# Timestamp range (first and last events in window)
_FIRST_TS=$(printf '%s\n' "$_WINDOW" | jq -rs '.[0].ts // "unknown"' 2>/dev/null | tr -d '\r' || echo "unknown")
_LAST_TS=$(printf '%s\n' "$_WINDOW" | jq -rs '.[-1].ts // "unknown"' 2>/dev/null | tr -d '\r' || echo "unknown")

# Generated timestamp
_GENERATED=$(date -u +"%Y-%m-%dT%H:%M:%SZ" 2>/dev/null || date +"%Y-%m-%dT%H:%M:%SZ")

# ── Recent escalations (last 10, escalated=true) ──────────────────────────────
_RECENT_ESCALATED=$(printf '%s\n' "$_WINDOW" | \
  jq -rs '.[] | select(.escalated == true) | "- \(.ts[0:10]) [\(.tier)] \(.task) → \(.outcome)"' \
  2>/dev/null | tail -10 || true)

# ── Write the bounded summary ─────────────────────────────────────────────────

# Body piped into sb_write_generated_page (frontmatter + atomic write handled there).
{
  printf '# Cost-Routing Patterns\n\n'
  printf '> Auto-generated by `cost-router-capture.sh`. Updated each session (Stop hook).\n'
  printf '> **Do not edit by hand** — changes will be overwritten.\n'
  printf '> Generated: %s | Events window: %s → %s\n\n' \
    "$_GENERATED" "$_FIRST_TS" "$_LAST_TS"

  printf '## Summary (%s events)\n\n' "$_TOTAL"
  printf '| Tier | Count | %% of Total |\n'
  printf '|------|-------|-------------|\n'
  awk -v do_c="$_DO_COUNT" -v think_c="$_THINK_COUNT" -v scout_c="$_SCOUT_COUNT" -v total="$_TOTAL" \
    'BEGIN {
      if (total > 0) {
        printf "| DO (Sonnet/implement) | %d | %.0f%% |\n", do_c, (do_c/total)*100
        printf "| THINK (Opus/plan) | %d | %.0f%% |\n", think_c, (think_c/total)*100
        printf "| SCOUT (Haiku/search) | %d | %.0f%% |\n", scout_c, (scout_c/total)*100
      }
    }'

  printf '\n## Escalation\n\n'
  printf -- '- **Total escalated to Opus:** %s of %s (%s)\n' \
    "$_ESCALATED" "$_TOTAL" "$_ESCALATE_RATE"
  printf -- '- **Outcomes reported ok:** %s of %s\n' "$_OK_COUNT" "$_TOTAL"
  printf -- '- **Committed results:** %s of %s\n\n' "$_COMMITTED" "$_TOTAL"

  if [ -n "$_RECENT_ESCALATED" ]; then
    printf '## Recent Escalations\n\n'
    printf '%s\n\n' "$_RECENT_ESCALATED"
  fi

  printf '## Notes\n\n'
  printf -- '- This page is read by `/cost-router:orchestrate` and `/cost-router:model-route` to bias future tier decisions.\n'
  printf -- '- High escalation rate suggests tasks arriving at DO tier are genuinely hard — consider adjusting classification thresholds.\n'
  printf -- '- Events file: `%s`\n' "$_EVENTS"
} | sb_write_generated_page "$_OUT" "Cost-Routing Patterns" \
    "Auto-generated routing telemetry: tier distribution, escalations, and outcomes from cost-router-events.jsonl" \
  2>/dev/null || true

# One-time legacy cleanup (R5.1 deep-review): the page used to live at wiki ROOT
# (unindexed by search, churned by knowledge_validate). A stale copy there would
# collide on slug with the new wiki/state/ page (duplicate_slug error with no
# autofix). Remove it ONLY if it is provably OUR generated page — the old writer
# always stamped this exact attribution line.
_LEGACY="$_KDIR/wiki/cost-routing-patterns.md"
if [ -f "$_LEGACY" ] && grep -q 'Auto-generated by .cost-router-capture.sh' "$_LEGACY" 2>/dev/null; then
  rm -f "$_LEGACY" 2>/dev/null || true
fi

exit 0
